#!/usr/bin/env python3
"""Write the Large Graph chapter of the visual inspection Blueprint.

The chapter needs a dependency graph at the scale of a real project, which is
too large to maintain by hand. A fixed seed keeps the output stable.

usage: generate_large_graph.py [--check]

With --check, exit nonzero if the checked-in chapter differs from the output.
"""
import argparse
import pathlib
import random
import sys

SEED = 20261105
GROUPS = 12
NODES_PER_GROUP = 20
DEFINITIONS_PER_GROUP = 4
ISOLATED_SHARE = 0.08
CROSS_GROUP_SHARE = 0.3
COMPLETE_SHARE = 0.45
SORRY_SHARE = 0.1
PROOF_SHARE = 0.2

TOPICS = [
    "Rings", "Modules", "Fields", "Valuations", "Completions", "Adeles",
    "Characters", "Representations", "Galois Groups", "Curves", "Forms",
    "Hecke Operators",
]

CHAPTER = pathlib.Path(__file__).resolve().parent.parent / "VisualInspection/Chapters/LargeGraph.lean"

HEADER = """\
-- Generated by scripts/generate_large_graph.py. Do not edit by hand.
import Verso
import VersoManual
import VersoBlueprint

open Verso.Genre
open Verso.Genre.Manual
open Informal

#doc (Manual) "Large Graph" =>

{count} blocks in {groups} groups, generated with a fixed seed. Real projects
reach this size: the FLT Blueprint has about 240 entries.

What to check:

* The dependency graph is readable when it first opens.
* Groups, statuses, and edges remain distinguishable at this scale.
* The Summary and this chapter stay usable with many entries.
"""


def label(group, index):
    return f"large_g{group:02d}_n{index:02d}"


def lean_name(group, index):
    return f"largeG{group:02d}N{index:02d}"


def generate():
    rng = random.Random(SEED)
    out = [HEADER.format(count=GROUPS * NODES_PER_GROUP, groups=GROUPS)]
    for group in range(GROUPS):
        topic = TOPICS[group]
        group_label = f"large_group_{group:02d}"
        out.append(f"# {topic}\n")
        out.append(f':::group "{group_label}"\n{topic}, a synthetic area of the large graph.\n:::\n')
        for index in range(NODES_PER_GROUP):
            node = label(group, index)
            is_definition = index < DEFINITIONS_PER_GROUP
            kind = "definition" if is_definition else rng.choice(["theorem", "lemma_", "lemma_", "proposition"])
            uses = []
            if index > 0 and rng.random() >= ISOLATED_SHARE:
                for _ in range(rng.randint(1, 3)):
                    if group > 0 and rng.random() < CROSS_GROUP_SHARE:
                        target = label(rng.randrange(group), rng.randrange(NODES_PER_GROUP))
                    else:
                        target = label(group, rng.randrange(index))
                    if target not in uses:
                        uses.append(target)
            refs = "".join(f' {{uses "{target}"}}[]' for target in uses)
            body = f"Synthetic {topic.lower()} entry {index}."
            if refs:
                body += f" It uses{refs}."
            out.append(f':::{kind} "{node}" (parent := "{group_label}")\n{body}\n:::\n')
            status = rng.random()
            if not is_definition and rng.random() < PROOF_SHARE and uses:
                out.append(f':::proof "{node}"\nThe proof follows from {{uses "{uses[0]}"}}[].\n:::\n')
            if status < COMPLETE_SHARE:
                code = (f"def {lean_name(group, index)} : Nat := {index}" if is_definition
                        else f"theorem {lean_name(group, index)} : True := trivial")
                out.append(f'```lean "{node}"\n{code}\n```\n')
            elif status < COMPLETE_SHARE + SORRY_SHARE and not is_definition:
                out.append(f'```lean "{node}"\ntheorem {lean_name(group, index)} : True := by\n  sorry\n```\n')
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if CHAPTER.read_text() != text:
            print(f"{CHAPTER} is out of date; run {pathlib.Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    CHAPTER.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
