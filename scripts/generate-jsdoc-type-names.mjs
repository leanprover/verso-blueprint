import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = path.join(packageRoot, "tests", "preview_runtime_api_contract.json");
const outputPath = path.join(packageRoot, "doc", "jsdoc-static", "jsdoc-type-names.js");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(message);
  process.exit(1);
}

function publicTypeExports(contract) {
  const typeExports = contract.typeExports;
  if (!Array.isArray(typeExports) || typeExports.length === 0) {
    fail(`${contractPath}: missing non-empty typeExports array`);
  }

  const seen = new Set();
  for (const typeName of typeExports) {
    if (typeof typeName !== "string" || !/^[A-Za-z][A-Za-z0-9_]*$/.test(typeName)) {
      fail(`${contractPath}: invalid public type name ${JSON.stringify(typeName)}`);
    }
    if (seen.has(typeName)) {
      fail(`${contractPath}: duplicate public type name ${typeName}`);
    }
    seen.add(typeName);
  }

  return typeExports;
}

function renderTypeNames(typeNames) {
  const typeNameLines = typeNames.map((typeName) => `    ${JSON.stringify(typeName)}`).join(",\n");
  return `// Generated by scripts/generate-jsdoc-type-names.mjs from tests/preview_runtime_api_contract.json.
// Run \`npm run docs\` after changing the public JavaScript API type contract.

(function (globalScope) {
  "use strict";

  globalScope.blueprintJSDocTypeNames = [
${typeNameLines}
  ];
})(typeof window === "undefined" ? globalThis : window);
`;
}

const contract = JSON.parse(await readFile(contractPath, "utf8"));
const source = renderTypeNames(publicTypeExports(contract));

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    fail(`${path.relative(packageRoot, outputPath)} is missing; run npm run docs`);
  }
  if (current !== source) {
    fail(`${path.relative(packageRoot, outputPath)} is stale; run npm run docs`);
  }
} else {
  await writeFile(outputPath, source, "utf8");
}
